-- 사용자와 외부 로그인 계정. 마이그레이션 버전 구간: user-auth V200–V299.
-- 한 사용자에 외부 계정(카카오 등)이 여럿 붙을 수 있고, (provider, subject)는 하나의 사용자만 가리킨다.

CREATE TABLE app_user (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname   VARCHAR(40) NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_identity (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    -- KAKAO: 카카오 회원번호, DEV: local 프로필 개발용 로그인의 닉네임
    provider   VARCHAR(20)  NOT NULL,
    subject    VARCHAR(100) NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_identity UNIQUE (provider, subject),
    CONSTRAINT fk_user_identity_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT ck_user_identity_provider CHECK (provider IN ('KAKAO', 'DEV'))
);
CREATE INDEX ix_user_identity_user ON user_identity (user_id);
