-- 기능 B(내 계좌) 테이블. 마이그레이션 버전은 모듈별로 나눠 쓴다: market-data V1–V99, portfolio V100–V199.
-- 다른 모듈이 나중에 낮은 버전을 추가해도 되도록 app의 spring.flyway.out-of-order를 켜 둔다.
--
-- 원시 데이터(account 제외)는 쌓기만 한다(append-only, 정정은 새 행). 브로커가 준 id로 중복 수집을 막는다.
-- 해외 종목의 price·fee·tax는 현지 통화, fx_rate는 그 체결의 원화 환율(원화 종목은 1)이다.

CREATE TABLE account (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    broker       VARCHAR(20)  NOT NULL,
    sample       BOOLEAN      NOT NULL DEFAULT FALSE,
    -- 수집을 시작한 날. 이 전의 일별 값은 체결 내역으로 역산(BACKFILLED)한다.
    connected_at DATE         NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_account_broker CHECK (broker IN ('TOSS'))
);

CREATE TABLE trade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT         NOT NULL,
    broker_trade_id VARCHAR(64)    NOT NULL,
    date            DATE           NOT NULL,
    instrument_id   BIGINT         NOT NULL,
    side            VARCHAR(4)     NOT NULL,
    quantity        NUMERIC(20, 6) NOT NULL,
    price           NUMERIC(20, 6) NOT NULL,
    fx_rate         NUMERIC(20, 6) NOT NULL,
    fee             NUMERIC(20, 6) NOT NULL DEFAULT 0,
    tax             NUMERIC(20, 6) NOT NULL DEFAULT 0,
    CONSTRAINT uq_trade_broker_id UNIQUE (account_id, broker_trade_id),
    CONSTRAINT fk_trade_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_trade_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (id),
    CONSTRAINT ck_trade_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_trade_positive CHECK (quantity > 0 AND price > 0 AND fx_rate > 0 AND fee >= 0 AND tax >= 0)
);
CREATE INDEX ix_trade_account_date ON trade (account_id, date);

-- 입금·출금(원). 배당은 dividend 테이블에 따로 둔다.
CREATE TABLE cash_flow (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT         NOT NULL,
    broker_flow_id VARCHAR(64)    NOT NULL,
    date           DATE           NOT NULL,
    type           VARCHAR(10)    NOT NULL,
    amount         NUMERIC(20, 2) NOT NULL,
    CONSTRAINT uq_cash_flow_broker_id UNIQUE (account_id, broker_flow_id),
    CONSTRAINT fk_cash_flow_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT ck_cash_flow_type CHECK (type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_cash_flow_amount CHECK (amount > 0)
);

-- 계좌에 들어온 배당(원, 세후).
CREATE TABLE dividend (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         BIGINT         NOT NULL,
    broker_dividend_id VARCHAR(64)    NOT NULL,
    date               DATE           NOT NULL,
    instrument_id      BIGINT         NOT NULL,
    amount             NUMERIC(20, 2) NOT NULL,
    CONSTRAINT uq_dividend_broker_id UNIQUE (account_id, broker_dividend_id),
    CONSTRAINT fk_dividend_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_dividend_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (id),
    CONSTRAINT ck_dividend_amount CHECK (amount >= 0)
);

-- 수집에 실패한 날(재시도 3회 실패). 로그에 MISSING 빈 칸으로 보인다.
CREATE TABLE collection_gap (
    account_id BIGINT       NOT NULL,
    date       DATE         NOT NULL,
    reason     VARCHAR(200) NOT NULL,
    CONSTRAINT pk_collection_gap PRIMARY KEY (account_id, date),
    CONSTRAINT fk_collection_gap_account FOREIGN KEY (account_id) REFERENCES account (id)
);

-- 파생: 원시 데이터를 리플레이한 일별 값. calc_version이 바뀌면 통째로 다시 계산한다.
-- MISSING인 날은 total_value·pnl이 0이고, 그 사이 손익은 다음 기록일에 몰아 넣는다.
CREATE TABLE account_day (
    account_id    BIGINT           NOT NULL,
    date          DATE             NOT NULL,
    source        VARCHAR(10)      NOT NULL,
    total_value   NUMERIC(20, 2)   NOT NULL,
    net_cash_flow NUMERIC(20, 2)   NOT NULL,
    pnl           NUMERIC(20, 2)   NOT NULL,
    daily_return  DOUBLE PRECISION NOT NULL,
    twr_index     DOUBLE PRECISION NOT NULL,
    calc_version  INT              NOT NULL,
    CONSTRAINT pk_account_day PRIMARY KEY (account_id, date),
    CONSTRAINT fk_account_day_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT ck_account_day_source CHECK (source IN ('COLLECTED', 'BACKFILLED', 'MISSING'))
);
