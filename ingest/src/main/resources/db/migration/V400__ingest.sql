-- 수집(ingest) 테이블. 마이그레이션 버전 구간: ingest V400–V499.
-- 작업 큐는 SELECT … FOR UPDATE SKIP LOCKED로 워커 여러 대가 같은 작업을 집지 않게 한다(PostgreSQL, H2 2.x 모두 지원).

CREATE TABLE ingest_job (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT           NOT NULL,
    kind         VARCHAR(10)      NOT NULL,
    -- DAILY는 수집 기준일(직전 거래일), BACKFILL은 null
    as_of        DATE,
    state        VARCHAR(10)      NOT NULL,
    attempts     INT              NOT NULL DEFAULT 0,
    next_run_at  TIMESTAMP        NOT NULL,
    locked_by    VARCHAR(100),
    locked_at    TIMESTAMP,
    -- 사용자에게 보여 줄 실패 사유(키 값은 넣지 않는다)와 사유 코드(BrokerException.Reason 등)
    last_error   VARCHAR(500),
    error_reason VARCHAR(40),
    progress     DOUBLE PRECISION NOT NULL DEFAULT 0,
    -- 운영용 메모(대사 불일치 등)
    note         VARCHAR(1000),
    created_at   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at  TIMESTAMP,
    CONSTRAINT fk_ingest_job_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT ck_ingest_job_kind CHECK (kind IN ('BACKFILL', 'DAILY')),
    CONSTRAINT ck_ingest_job_state CHECK (state IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_ingest_job_progress CHECK (progress >= 0 AND progress <= 1)
);
CREATE INDEX ix_ingest_job_ready ON ingest_job (state, next_run_at);
CREATE INDEX ix_ingest_job_account ON ingest_job (account_id, kind, id);

-- 일일 수집 때 받은 보유 종목(증권사 표시값). 리플레이 결과와 맞춰 보는 데 쓴다. 가격은 거래 통화.
CREATE TABLE holding_snapshot (
    account_id BIGINT         NOT NULL,
    date       DATE           NOT NULL,
    symbol     VARCHAR(20)    NOT NULL,
    quantity   NUMERIC(20, 6) NOT NULL,
    avg_price  NUMERIC(20, 6) NOT NULL,
    last_price NUMERIC(20, 6) NOT NULL,
    currency   VARCHAR(3)     NOT NULL,
    CONSTRAINT pk_holding_snapshot PRIMARY KEY (account_id, date, symbol),
    CONSTRAINT fk_holding_snapshot_account FOREIGN KEY (account_id) REFERENCES account (id)
);

-- 일일 수집 때 받은 현금(매수 가능 금액). krw는 원, usd는 달러, fx는 그날 USD/KRW. 현금흐름 추정의 기준.
CREATE TABLE cash_snapshot (
    account_id BIGINT         NOT NULL,
    date       DATE           NOT NULL,
    krw        NUMERIC(20, 2) NOT NULL,
    usd        NUMERIC(20, 2) NOT NULL,
    fx         NUMERIC(20, 6) NOT NULL,
    CONSTRAINT pk_cash_snapshot PRIMARY KEY (account_id, date),
    CONSTRAINT fk_cash_snapshot_account FOREIGN KEY (account_id) REFERENCES account (id)
);

-- 새 체결을 어디까지 받았는지(주문 시각 기준). 다음 수집은 며칠 겹쳐 받고 broker_trade_id로 중복을 거른다.
CREATE TABLE sync_cursor (
    account_id    BIGINT    NOT NULL PRIMARY KEY,
    last_order_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_sync_cursor_account FOREIGN KEY (account_id) REFERENCES account (id)
);
