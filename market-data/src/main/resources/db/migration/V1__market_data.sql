-- 시세(공용) 테이블. PostgreSQL이 운영 DB이고, 로컬은 H2(PostgreSQL 모드)로 같은 스크립트를 돌린다.
-- 두 DB에서 모두 도는 문법만 쓴다(IDENTITY, NUMERIC, CHECK).
-- 로컬 H2는 2.5.250 이상이어야 한다: 2.4.240은 문자열 CHECK 제약을 만든 세션(Flyway 커넥션)이 닫히면
-- 이후 INSERT가 "Check constraint invalid"로 실패한다(gradle/libs.versions.toml에서 버전 고정).

CREATE TABLE instrument (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(20)  NOT NULL,
    name     VARCHAR(200) NOT NULL,
    market   VARCHAR(20)  NOT NULL,
    currency VARCHAR(3)   NOT NULL,
    type     VARCHAR(10)  NOT NULL,
    sample   BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_instrument_code UNIQUE (code),
    CONSTRAINT ck_instrument_type CHECK (type IN ('ETF', 'INDEX', 'STOCK'))
);

-- 행이 있는 날이 곧 그 종목의 거래일이다(calc-engine의 PriceSeries가 이 날짜를 거래일로 쓴다).
CREATE TABLE daily_price (
    instrument_id BIGINT        NOT NULL,
    date          DATE          NOT NULL,
    close         NUMERIC(20, 4) NOT NULL,
    adj_close     NUMERIC(20, 4),
    dividend      NUMERIC(20, 4),
    CONSTRAINT pk_daily_price PRIMARY KEY (instrument_id, date),
    CONSTRAINT fk_daily_price_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (id),
    CONSTRAINT ck_daily_price_close CHECK (close > 0)
);
